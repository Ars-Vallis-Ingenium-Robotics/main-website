"""Builds the fonts a brand can pick for reports (/admin/branding) from tools/fonts/fonts.json.

Writes, from scratch each time:
- src/AviSite.Web/wwwroot/fonts/brand/*.woff2   web report (Latin subset, one file per weight)
- src/AviSite.Web/wwwroot/css/brand-fonts.css   their @font-face rules
- src/AviSite.Web/Pdf/Fonts/*.ttf               static TrueType for the PDF writer (no WOFF2 or variable fonts in PDFs)
- src/AviSite.Web/Store/BrandFonts.Catalog.g.cs the list the app shows and uses

Fonts are SIL OFL 1.1 (each family's license is copied next to its .ttf) except Porcine Heavy, AVI's display
face (see wwwroot/fonts/FONTS.md). Fontsource packages come from npm:

    pip install fonttools brotli
    mkdir -p /tmp/fontpk && cd /tmp/fontpk
    for p in $(python -c "import json;print(' '.join(f['id'] for f in json.load(open('<repo>/tools/fonts/fonts.json'))['fonts'] if f.get('source')!='site'))"); do
      npm pack @fontsource/$p && mkdir -p $p && tar xzf fontsource-$p-*.tgz -C $p; done
    python tools/fonts/make_pdf_fonts.py /tmp/fontpk
"""
import json
import shutil
import sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

root = Path(__file__).resolve().parents[2]
spec = json.loads((root / "tools/fonts/fonts.json").read_text())
site_fonts = root / "src/AviSite.Web/wwwroot/fonts"
web_out = site_fonts / "brand"
pdf_out = root / "src/AviSite.Web/Pdf/Fonts"
css_out = root / "src/AviSite.Web/wwwroot/css/brand-fonts.css"
cs_out = root / "src/AviSite.Web/Store/BrandFonts.Catalog.g.cs"
packages = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/tmp/fontpk")

for d, patterns in ((web_out, ["*.woff2"]), (pdf_out, ["*.ttf", "*-LICENSE.txt"])):
    d.mkdir(parents=True, exist_ok=True)
    for p in patterns:
        for f in d.glob(p):
            f.unlink()

def save_ttf(src, dest, axes=None):
    f = TTFont(src)
    if axes:
        f = instancer.instantiateVariableFont(f, axes, updateFontNames=False)
    f.flavor = None
    f.save(dest)

SITE_FILES = {"Porcine": "porcine-heavy.woff2", "Archivo": "archivo-var.woff2", "JetBrains Mono": "jetbrains-mono-var.woff2"}
css = ["/* Fonts a brand can pick for its reports (/admin/branding). Loaded only on report and branding pages.",
       "   Generated by tools/fonts/make_pdf_fonts.py from tools/fonts/fonts.json; don't edit by hand.",
       "   SIL Open Font License 1.1. Porcine, Archivo and JetBrains Mono come from site.css. */"]
entries = []
for f in spec["fonts"]:
    fid, regular, bold, heading = f["id"], f.get("regular"), f.get("bold"), f["heading"]
    files = {}  # role -> pdf file name
    if f.get("source") == "site":
        src = site_fonts / SITE_FILES[f["css"]]
        variable = "fvar" in TTFont(src)
        width = 125 if f.get("stretch") == "125%" else 100
        def axes(w):
            if not variable:
                return None
            a = {"wght": w}
            if "wdth" in [x.axisTag for x in TTFont(src)["fvar"].axes]:
                a["wdth"] = width
            return a
        weights = {"regular": regular, "bold": bold, "heading": heading}
    else:
        pkg = next((packages / fid).rglob("files"))
        def src_for(w):
            return next(pkg.glob(f"*-latin-{w}-normal.woff2"))
        weights = {"regular": regular, "bold": bold, "heading": heading}
        lic = next((packages / fid).rglob("LICENSE"), None)
        if lic:
            shutil.copyfile(lic, pdf_out / f"{fid}-LICENSE.txt")
    done = {}
    for role, w in weights.items():
        if w is None:
            continue
        if w in done:  # same weight as another role: share the file
            files[role] = done[w]
            continue
        name = f"{fid}-{role}.ttf"
        if f.get("source") == "site":
            save_ttf(src, pdf_out / name, axes(w))
        else:
            save_ttf(src_for(w), pdf_out / name)
            shutil.copyfile(src_for(w), web_out / f"{fid}-{w}.woff2")
            css.append(f'@font-face {{ font-family: "Brand {f["label"]}"; src: url("/fonts/brand/{fid}-{w}.woff2") format("woff2"); font-weight: {w}; font-display: swap; }}')
        files[role] = done[w] = name
    family = f.get("css") or f"Brand {f['label']}"
    def q(v):
        return "null" if v is None else f'"{v}"'
    entries.append(f'        new({q(fid)}, {q(f["label"])}, {q(family)}, {q(f["group"])}, {heading}, {q(files["heading"])}, '
                   f'{q(files.get("regular"))}, {q(files.get("bold"))}, {q(f.get("stretch"))}, {regular or 400}),')

css_out.write_text("\n".join(css) + "\n")
groups = ", ".join(f'"{g}"' for g in spec["groups"])
cs_out.write_text(f"""// <auto-generated> by tools/fonts/make_pdf_fonts.py from tools/fonts/fonts.json. Don't edit by hand. </auto-generated>
namespace AviSite.Web.Store;

public static partial class BrandFonts
{{
    /// <summary>Picker groups, in order.</summary>
    public static readonly string[] Groups = [{groups}];

    public static readonly BrandFont[] All =
    [
{chr(10).join(entries)}
    ];
}}
""")
total = sum(p.stat().st_size for p in pdf_out.glob("*.ttf"))
web = sum(p.stat().st_size for p in web_out.glob("*.woff2"))
print(f"{len(entries)} fonts · PDF {total // 1024} KB · web {web // 1024} KB")
